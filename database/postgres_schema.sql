-- Online Entertainment PostgreSQL 16 schema, applied on Neon Free / polyoe.
-- For a NEW EMPTY PostgreSQL database only. Original SQL Server scripts are unchanged.
CREATE TABLE users (
 id VARCHAR(20) PRIMARY KEY, password VARCHAR(255) NOT NULL,
 fullname VARCHAR(50) NOT NULL, email VARCHAR(50) NOT NULL,
 admin BOOLEAN NOT NULL DEFAULT FALSE, channelname VARCHAR(100),
 channeldescription VARCHAR(500)
);
CREATE TABLE video (
 id VARCHAR(20) PRIMARY KEY, title VARCHAR(255) NOT NULL,
 poster VARCHAR(255), views INTEGER NOT NULL DEFAULT 0,
 description TEXT, active BOOLEAN NOT NULL DEFAULT TRUE,
 uploaderid VARCHAR(20) REFERENCES users(id),
 sourceurl VARCHAR(1024), sourcetype VARCHAR(20),
 createdat TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE favorite (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 userid VARCHAR(20) NOT NULL REFERENCES users(id),
 videoid VARCHAR(20) NOT NULL REFERENCES video(id),
 likedate DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT uq_favorite_user_video UNIQUE (userid, videoid)
);
CREATE TABLE share (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 userid VARCHAR(20) NOT NULL REFERENCES users(id),
 videoid VARCHAR(20) NOT NULL REFERENCES video(id),
 emails VARCHAR(255) NOT NULL,
 sharedate DATE NOT NULL DEFAULT CURRENT_DATE
);
CREATE INDEX idx_video_public_recent ON video(active, createdat DESC);
CREATE INDEX idx_video_uploader ON video(uploaderid, createdat DESC);
